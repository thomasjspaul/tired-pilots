// Generates public/_redirects for Cloudflare Pages from:
//   1. src/data/legacy-redirects.json  (old Google Sites URLs -> new paths)
//   2. every non-empty `legacyPaths` in src/content/**/*.md(x) frontmatter
//
// Runs in `prebuild`. The output is committed so diffs are visible and CI can
// check it with scripts/check-redirects.mjs.

import { readFile, readdir, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { join, extname } from 'node:path';
import { parse as parseYaml } from 'yaml';

const root = fileURLToPath(new URL('..', import.meta.url));

/** Map a content collection folder + file to its published path. */
function contentPath(collection, id) {
  const slug = id.replace(/^en\//, '').replace(/\.mdx?$/, '');
  if (collection === 'regulations') return `/rules/${slug}`;
  if (collection === 'explainers') return `/qa/${slug}`;
  if (collection === 'pages') return `/${slug === 'home' ? '' : slug}`;
  return null;
}

async function walk(dir) {
  const out = [];
  for (const entry of await readdir(dir, { withFileTypes: true })) {
    const p = join(dir, entry.name);
    if (entry.isDirectory()) out.push(...(await walk(p)));
    else if (['.md', '.mdx'].includes(extname(entry.name))) out.push(p);
  }
  return out;
}

async function fromFrontmatter() {
  const base = join(root, 'src/content');
  const rules = [];
  for (const file of await walk(base)) {
    const rel = file.slice(base.length + 1).replace(/\\/g, '/');
    const [collection, ...rest] = rel.split('/');
    const id = rest.join('/');
    const text = await readFile(file, 'utf8');
    const m = /^---\n([\s\S]*?)\n---/.exec(text);
    if (!m) continue;
    let fm;
    try {
      fm = parseYaml(m[1]);
    } catch {
      continue;
    }
    const legacy = fm?.legacyPaths;
    const to = fm?.slug ? contentPath(collection, `en/${fm.slug}`) : contentPath(collection, id);
    if (!Array.isArray(legacy) || !to) continue;
    for (const from of legacy) rules.push({ from, to, status: 301 });
  }
  return rules;
}

const json = JSON.parse(await readFile(join(root, 'src/data/legacy-redirects.json'), 'utf8'));

const all = [...json, ...(await fromFrontmatter())]
  // drop no-ops (old path === new path)
  .filter((r) => r.from !== r.to && r.from !== r.to.split('#')[0]);

// de-dupe by `from`, expand trailing-slash and %20 variants
const seen = new Set();
const lines = [];
for (const { from, to, status = 301 } of all) {
  for (const variant of new Set([from, from.replace(/\/$/, ''), `${from.replace(/\/$/, '')}/`])) {
    if (seen.has(variant)) continue;
    seen.add(variant);
    lines.push(`${variant}  ${to}  ${status}`);
  }
}
lines.sort();

const header = `# Generated by scripts/gen-redirects.mjs — do not edit by hand.
# Sources: src/data/legacy-redirects.json + content frontmatter legacyPaths.
`;

await writeFile(join(root, 'public/_redirects'), header + lines.join('\n') + '\n', 'utf8');
console.log(`[gen-redirects] wrote ${lines.length} rules to public/_redirects`);
