// Generates public/_redirects from the legacy URL map plus every `legacyPaths`
// entry declared in content frontmatter.
//
// STATUS: stub. Filled in during Stage 4 (Search, polish, launch). For now it
// writes a header-only file so `npm run build` has a deterministic input.

import { writeFile, mkdir } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { dirname } from 'node:path';

const outUrl = new URL('../public/_redirects', import.meta.url);
const outPath = fileURLToPath(outUrl);

const header = `# This file is generated by scripts/gen-redirects.mjs — do not edit by hand.
# Stage 4 populates it from src/data/legacyMap.ts and content \`legacyPaths\`.
`;

await mkdir(dirname(outPath), { recursive: true });
await writeFile(outPath, header, 'utf8');
console.log('[gen-redirects] wrote placeholder public/_redirects');
